/**
 * @fileoverview Generates one small, standalone CSS file per gallery/template theme so a
 * consumer can opt into a single preset without loading the docs adapter's JS at all — e.g.
 * `<link rel="stylesheet" href="/assets/themes/simple-dark.css">` plus
 * `element.dataset.hawkThemePreset = 'simple-dark'`. Each file only ever contains that one
 * theme's `--hawk-*` custom properties (a few dozen declarations), so per-theme cost stays a
 * handful of bytes gzipped regardless of how many presets the gallery grows to — the opposite of
 * bundling every theme's tokens into one shared file a page would load in full either way.
 *
 * Source of truth stays singular: this reads the same HAWK_GALLERY_THEMES / theme-templates/*.json
 * that docs/static/assets/hawk-docs-adapter.mjs already exports/consumes, so a theme's tokens are
 * never hand-duplicated between the adapter and these files — edit the source, then re-run this.
 * @module scripts/generate-theme-css
 */

import { existsSync, mkdirSync, readFileSync, readdirSync, unlinkSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

import {
  HAWK_GALLERY_TEMPLATE_IDS,
  HAWK_GALLERY_THEMES,
  createHawkGalleryThemeFromTemplate,
} from '../docs/static/assets/hawk-docs-adapter.mjs';

const outDir = resolve('docs/static/assets/themes');
// Generous relative to real output (~250-750 bytes/theme observed) — catches a token dump or a
// hand-edit gone wrong, not a tight budget meant to be raised repeatedly like check:size's.
const maxBytesPerFile = 3 * 1024;

mkdirSync(outDir, { recursive: true });

const templateIds = new Set(HAWK_GALLERY_TEMPLATE_IDS);
const templateThemes = HAWK_GALLERY_TEMPLATE_IDS.map((id) => {
  const templatePath = resolve(`theme-templates/${id}.json`);
  const template = JSON.parse(readFileSync(templatePath, 'utf8'));
  return createHawkGalleryThemeFromTemplate(id, template);
}).filter(Boolean);

const themes = [...HAWK_GALLERY_THEMES, ...templateThemes];

function renderCss(theme) {
  const declarations = Object.entries(theme.tokens)
    .filter(([, value]) => value !== null && value !== undefined)
    .map(([token, value]) => `  ${token}: ${value};`)
    .join('\n');

  const source = templateIds.has(theme.id)
    ? `theme-templates/${theme.id}.json`
    : 'docs/static/assets/hawk-docs-adapter.mjs (HAWK_GALLERY_THEMES)';

  return `/*!
 * ${theme.label} — generated by scripts/generate-theme-css.mjs. Do not hand-edit: change this
 * theme's tokens in ${source}, then re-run the generator.
 * ${theme.description}
 */

[data-hawk-theme-preset='${theme.id}'] {
${declarations}
}
`;
}

const written = [];
for (const theme of themes) {
  const css = renderCss(theme);
  const bytes = Buffer.byteLength(css, 'utf8');
  if (bytes > maxBytesPerFile) {
    throw new Error(
      `docs/static/assets/themes/${theme.id}.css is ${bytes} bytes, over the ${maxBytesPerFile}-byte per-theme budget.`
    );
  }
  writeFileSync(resolve(outDir, `${theme.id}.css`), css);
  written.push({ id: theme.id, bytes });
}

// Remove generated files for themes that no longer exist, so stale presets don't linger.
const currentIds = new Set(themes.map((theme) => theme.id));
if (existsSync(outDir)) {
  for (const file of readdirSync(outDir)) {
    const id = file.replace(/\.css$/, '');
    if (file.endsWith('.css') && !currentIds.has(id)) {
      unlinkSync(resolve(outDir, file));
    }
  }
}

console.log(`Generated ${written.length} theme CSS files in ${outDir}:`);
for (const { id, bytes } of written) {
  console.log(`  ${id}.css — ${bytes} bytes`);
}
